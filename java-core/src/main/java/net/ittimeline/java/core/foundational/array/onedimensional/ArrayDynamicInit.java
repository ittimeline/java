package net.ittimeline.java.core.foundational.array.onedimensional;

/**
 * 一维数组动态初始化
 *
 * @author tony 18601767221@163.com
 * @version 2026/10/8 9:30
 * @since Java 25
 */
public class ArrayDynamicInit {
    static void main() {
        //数组声明
        int[] data;
        //数组动态初始化语法格式：数组名 =new 数据类型 [数组的长度];
        data = new int[5];


        //数组的声明和动态初始化合并语法格式: 数据类型[] 数组名 =new 数据类型 [数组的长度];
        String[] food = new String[108];
    }
}
