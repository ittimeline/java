package net.ittimeline.java.core.foundational.operator.assignment;

/**
 * 位运算复合赋值运算符使用
 *
 * @author tony 18601767221@163.com
 * @version 2026/10/4 15:16
 * @since Java 25
 */
public class BitwiseAssignmentOperator {
    static void main() {
        // 按位与复合赋值
        int x = 0b1100;              // 12
        //  x = x & 0b1010;
        x &= 0b1010;                 // 按位与：12 & 10 = 8 (1000)
        System.out.println("x &= 10  => " + x);   // 8

        // 按位或复合赋值
        int y = 0b1100;              // 12
        // y = y | 0b1010;
        y |= 0b1010;                 // 按位或：12 | 10 = 14 (1110)
        System.out.println("y |= 10  => " + y);   // 14

        // 按位异或复合赋值
        int z = 0b1100;              // 12
        //  z = z ^ 0b1010;
        z ^= 0b1010;                 // 按位异或：12 ^ 10 = 6 (0110)
        System.out.println("z ^= 10  => " + z);   // 6

        // 左移复合赋值
        int o = 8;                   // 二进制 1000
        // o = o << 2;
        o <<= 2;                     // 左移2位：1000 -> 100000 (32)
        System.out.println("o <<= 2  => " + o);   // 32

        // 带符号右移复合赋值
        int p = 16;                  // 二进制 10000
        //  p = p >> 2;
        p >>= 2;                     // 右移2位：10000 -> 100 (4)
        System.out.println("p >>= 2  => " + p);   // 4

        // 负数带符号右移（高位补1，相当于除以2^n并向负无穷取整）
        // 例如 -5 >> 1 等价于 -5 / 2 = -2.5 向下取整得 -3
        int q = -5;                  // 补码 11111111 11111111 11111111 11111011
        //q = q >> 1;
        q >>= 1;                     // 算术右移1位 → 11111111 11111111 11111111 11111101 = -3
        System.out.println("q >>= 1 => " + q);   // -3

        // 无符号右移复合赋值（高位始终补0，负数变成大正数）
        int r = -16;                 // 补码 11111111 11111111 11111111 11110000
        // r = r >>> 2;
        r >>>= 2;                    // 无符号右移2位 → 00111111 11111111 11111111 11111100 = 1073741820
        System.out.println("r >>>= 2 => " + r);   // 1073741820
    }


}
